// クリーンアップされたCapsLock LED制御関数
bool led_update_user(led_t led_state) {
    if (led_state.caps_lock) {
        writePinLow(GP25);  // CapsLockオンでQuantizerのLEDを点灯
    } else {
        writePinHigh(GP25); // CapsLockオフで消灯
    }
    return true;
}
